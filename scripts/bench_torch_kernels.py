#!/usr/bin/env python
"""Time the PyTorch eager oracles for the two fused kernels and an sgemm peak.

These are the baselines the SYCL kernels are compared against. The same
float32 shapes and the same reference functions are used by
``scripts/run_sycl.py``.

Usage:
    taskset -c 0,1 python scripts/bench_torch_kernels.py --runs 40
"""

from __future__ import annotations

import argparse
import json
import pathlib
import statistics
import sys
import time

import torch

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from tritonforge.reference import rmsnorm_residual_reference, swiglu_reference  # noqa: E402

SHAPES = {
    "swiglu": [(512, 4864), (1, 896), (17, 1000), (3, 895)],
    "rmsnorm_residual": [(4096, 896), (1, 896), (7, 1000), (3, 895)],
}
BYTES_PER_ELEMENT = {"swiglu": 12, "rmsnorm_residual": 16}
FLOPS_PER_ELEMENT = {"swiglu": 5, "rmsnorm_residual": 6}


def p95(values: list[float]) -> float:
    ordered = sorted(values)
    index = (len(ordered) - 1) * 0.95
    low = int(index)
    high = min(low + 1, len(ordered) - 1)
    return ordered[low] * (1 - (index - low)) + ordered[high] * (index - low)


def measure(fn, runs: int) -> list[float]:
    for _ in range(5):
        fn()
    times = []
    for _ in range(runs):
        start = time.perf_counter()
        fn()
        times.append((time.perf_counter() - start) * 1000.0)
    return times


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--runs", type=int, default=40)
    parser.add_argument("--out", default=str(ROOT / "results/x/torch_kernels.json"))
    args = parser.parse_args()

    torch.set_num_threads(2)
    generator = torch.Generator().manual_seed(0)
    hw = json.loads((ROOT / "results/x/hardware.json").read_text())["cpu"]["model_name"]
    rows = []

    for op, shapes in SHAPES.items():
        for m, n in shapes:
            gate = torch.empty(m, n).uniform_(-1, 1, generator=generator)
            up = torch.empty(m, n).uniform_(-1, 1, generator=generator)
            weight = torch.empty(n).uniform_(0.5, 1.0, generator=generator)
            x = torch.empty(m, n).uniform_(-1, 1, generator=generator)
            residual = torch.empty(m, n).uniform_(-1, 1, generator=generator)

            if op == "swiglu":
                with torch.no_grad():
                    times = measure(lambda gate=gate, up=up: swiglu_reference(gate, up), args.runs)
            else:
                with torch.no_grad():
                    times = measure(
                        lambda x=x, residual=residual, weight=weight: rmsnorm_residual_reference(
                            x, residual, weight
                        ),
                        args.runs,
                    )
            mean = statistics.fmean(times)
            elements = m * n
            rows.append(
                {
                    "op": op,
                    "m": m,
                    "n": n,
                    "runs": args.runs,
                    "ms_mean": mean,
                    "ms_p95": p95(times),
                    "gbps": elements * BYTES_PER_ELEMENT[op] / mean / 1e6,
                    "gflops": elements * FLOPS_PER_ELEMENT[op] / mean / 1e6,
                }
            )
            print(f"{op} {m}x{n}: {mean:.3f} ms")

    side = 2048
    a = torch.randn(side, side, generator=generator)
    b = torch.randn(side, side, generator=generator)
    with torch.no_grad():
        times = measure(lambda: a @ b, 20)
    gemm_ms = statistics.fmean(times)
    gemm_gflops = 2 * side**3 / gemm_ms / 1e6
    print(f"sgemm {side}^3: {gemm_ms:.1f} ms, {gemm_gflops:.1f} GFLOP/s")

    payload = {
        "hardware_cpu": hw,
        "note": "Generated by scripts/bench_torch_kernels.py (PyTorch fp32 eager, 2 threads).",
        "pytorch_version": torch.__version__,
        "rows": rows,
        "sgemm": {
            "side": side,
            "ms_mean": gemm_ms,
            "gflops_measured": gemm_gflops,
        },
    }
    out = pathlib.Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(payload, indent=2) + "\n")
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
