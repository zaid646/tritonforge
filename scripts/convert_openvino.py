#!/usr/bin/env python
"""Export Qwen2.5-0.5B-Instruct to OpenVINO IR in several weight formats.

Every conversion is a real ``optimum-cli export openvino`` run; the script
records wall time, on-disk size and the exact command in
``results/x/models.json``. Existing variants are reused unless ``--force`` is
given, so the expensive data-aware run is not repeated unnecessarily.

Usage:
    python scripts/convert_openvino.py \
        --models-dir /content/models \
        --out results/x/models.json
"""

from __future__ import annotations

import argparse
import json
import pathlib
import shutil
import subprocess
import time

ROOT = pathlib.Path(__file__).resolve().parents[1]
MODEL_ID = "Qwen/Qwen2.5-0.5B-Instruct"

VARIANTS: dict[str, dict] = {
    "fp16": {
        "label": "OpenVINO fp16 weights",
        "args": ["--weight-format", "fp16"],
        "data_aware": False,
    },
    "int8": {
        "label": "OpenVINO int8 weight-only",
        "args": ["--weight-format", "int8"],
        "data_aware": False,
    },
    "int4_g128": {
        "label": "OpenVINO int4 group-128",
        "args": ["--weight-format", "int4", "--group-size", "128"],
        "data_aware": False,
    },
    "int4_awq_g128": {
        "label": "OpenVINO int4 group-128 AWQ + scale estimation",
        "args": [
            "--weight-format",
            "int4",
            "--group-size",
            "128",
            "--awq",
            "--dataset",
            "wikitext2",
            "--num-samples",
            "64",
            "--scale-estimation",
        ],
        "data_aware": True,
    },
}


def dir_size_mb(path: pathlib.Path) -> tuple[float, float]:
    """Return (IR weights MB, whole directory MB)."""
    weights = 0
    total = 0
    for item in path.rglob("*"):
        if not item.is_file():
            continue
        size = item.stat().st_size
        total += size
        if item.name in {"openvino_model.bin", "openvino_model.xml"}:
            weights += size
    return round(weights / 1e6, 1), round(total / 1e6, 1)


def hardware_cpu() -> str:
    path = ROOT / "results/x/hardware.json"
    if not path.exists():
        raise SystemExit("results/x/hardware.json missing; run scripts/probe_hardware.py first")
    return json.loads(path.read_text())["cpu"]["model_name"]


def export_one(name: str, spec: dict, models_dir: pathlib.Path, force: bool) -> dict:
    out = models_dir / f"ov_{name}"
    command = [
        "optimum-cli",
        "export",
        "openvino",
        "--model",
        MODEL_ID,
        *spec["args"],
        str(out),
    ]
    if out.exists() and not force:
        print(f"[{name}] exists, skipping conversion")
        seconds = None
    else:
        if out.exists():
            shutil.rmtree(out)
        print(f"[{name}] {' '.join(command)}", flush=True)
        start = time.perf_counter()
        proc = subprocess.run(command, capture_output=True, text=True, check=False)
        seconds = round(time.perf_counter() - start, 1)
        log = ROOT / "artifacts/x/convert"
        log.mkdir(parents=True, exist_ok=True)
        (log / f"{name}.log").write_text(proc.stdout + "\n" + proc.stderr)
        if proc.returncode != 0:
            raise RuntimeError(f"conversion {name} failed; see artifacts/x/convert/{name}.log")
        print(f"[{name}] done in {seconds}s")

    weights_mb, total_mb = dir_size_mb(out)
    return {
        "variant": name,
        "label": spec["label"],
        "data_aware": spec["data_aware"],
        "path": str(out),
        "command": " ".join(command),
        "conversion_seconds": seconds,
        "ir_weights_mb": weights_mb,
        "total_dir_mb": total_mb,
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--models-dir", default="/content/models")
    parser.add_argument("--out", default=str(ROOT / "results/x/models.json"))
    parser.add_argument("--variants", nargs="*", default=list(VARIANTS))
    parser.add_argument("--force", action="store_true")
    args = parser.parse_args()

    models_dir = pathlib.Path(args.models_dir)
    models_dir.mkdir(parents=True, exist_ok=True)

    rows = []
    for name in args.variants:
        if name not in VARIANTS:
            raise SystemExit(f"unknown variant {name}; choose from {sorted(VARIANTS)}")
        rows.append(export_one(name, VARIANTS[name], models_dir, args.force))

    baseline = next((row for row in rows if row["variant"] == "fp16"), None)
    for row in rows:
        row["size_vs_fp16_pct"] = (
            round(100.0 * (1 - row["ir_weights_mb"] / baseline["ir_weights_mb"]), 1)
            if baseline and baseline["ir_weights_mb"]
            else None
        )

    payload = {
        "model_id": MODEL_ID,
        "hardware_cpu": hardware_cpu(),
        "note": "Generated by scripts/convert_openvino.py; sizes are measured files on disk.",
        "variants": rows,
    }
    out = pathlib.Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(payload, indent=2) + "\n")

    print(f"\n{'variant':18s} {'weights MB':>10s} {'total MB':>9s} {'vs fp16':>8s} {'time s':>7s}")
    for row in rows:
        print(
            f"{row['variant']:18s} {row['ir_weights_mb']:10.1f} {row['total_dir_mb']:9.1f} "
            f"{str(row['size_vs_fp16_pct'] or '-'):>8s} {str(row['conversion_seconds'] or '-'):>7s}"
        )
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
